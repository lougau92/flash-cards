"""Generate a content-versioned, same-origin offline app shell after Flutter builds."""
import hashlib
import json
import sys
from pathlib import Path
from urllib.parse import quote

root = Path(sys.argv[1] if len(sys.argv) > 1 else 'app/build/web')
for required in ['index.html', 'flutter_bootstrap.js', 'main.dart.js', 'manifest.json']:
    if not (root / required).is_file():
        raise SystemExit(f'Missing build output: {required}')

# Use our worker, and never publish source maps.
(root / 'flutter_service_worker.js').unlink(missing_ok=True)
for path in root.rglob('*.map'):
    path.unlink()
files = sorted(p for p in root.rglob('*') if p.is_file()
               and p.name not in {'service_worker.js', '.nojekyll'})
digest = hashlib.sha256()
for path in files:
    digest.update(path.relative_to(root).as_posix().encode())
    digest.update(path.read_bytes())
assets = ['./' + quote(p.relative_to(root).as_posix()) for p in files]
worker = '''// Generated by tool/prepare_pwa.py; cache only the shipped app assets.
const CACHE_PREFIX = 'flash-cards-shell-';
const CACHE_NAME = CACHE_PREFIX + __VERSION__;
const ASSETS = __ASSETS__;
const assetUrls = new Set(ASSETS.map(path => new URL(path, self.registration.scope).href));
self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    await cache.addAll(ASSETS);
    await self.skipWaiting();
  })());
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter(key => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME)
      .map(key => caches.delete(key)));
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin ||
      !url.href.startsWith(self.registration.scope)) return;
  const shell = new URL('./index.html', self.registration.scope).href;
  const key = request.mode === 'navigate' ? shell : url.href;
  // Never cache API responses or arbitrary same-origin requests.
  if (!assetUrls.has(key)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    return (await cache.match(key)) || fetch(request);
  })());
});
'''
worker = worker.replace('__VERSION__', json.dumps(digest.hexdigest()[:20]))
worker = worker.replace('__ASSETS__', json.dumps(assets))
(root / 'service_worker.js').write_text(worker)
(root / '.nojekyll').touch()
print(f'Prepared offline shell: {len(assets)} files, version {digest.hexdigest()[:20]}')
